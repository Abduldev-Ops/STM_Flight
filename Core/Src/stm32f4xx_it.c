/* Every interrupt WITHOUT its own handler lands here (the startup file's
 * Default_Handler now branches to this instead of looping forever).
 * It reports the IRQ number, switches that interrupt off so it can't fire
 * again, and returns, so the board keeps running instead of hanging. */
volatile uint32_t unexpected_irq_num   = 0xFFFFFFFF;   /* visible in Live Expressions */
volatile uint32_t unexpected_irq_count = 0;

void Unexpected_IRQ_Handler(void)
{
    uint32_t exc = __get_IPSR();          /* active exception number */
    unexpected_irq_count++;
    unexpected_irq_num = exc;

    if (exc >= 16)                        /* peripheral IRQ: disable it and carry on */
    {
        IRQn_Type irq = (IRQn_Type)(exc - 16);
        NVIC_DisableIRQ(irq);
        NVIC_ClearPendingIRQ(irq);
        huart3.Lock   = HAL_UNLOCKED;
        huart3.gState = HAL_UART_STATE_READY;
        printf("\r\n[IRQ] unexpected interrupt: IRQ %lu (exception %lu) - disabled it\r\n",
               (unsigned long)irq, (unsigned long)exc);
        return;
    }

    /* A core exception with no handler: stop safely and let the IWDG reset us */
    __disable_irq();
    TIM1->BDTR &= ~TIM_BDTR_MOE;
    for (;;);
}

