/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
	  irq_usart3++;
	  uint32_t sr = USART3->SR;
	  if (sr & (USART_SR_RXNE | USART_SR_ORE | USART_SR_FE | USART_SR_NE | USART_SR_PE))
	  {
	      uint8_t b = (uint8_t)USART3->DR;          // SR-then-DR read clears RXNE + all error flags
	      if (sr & (USART_SR_FE | USART_SR_NE | USART_SR_PE))
	          rc_uart_errors++;                     // corrupted byte: count and drop
	      else
	          RC_RxByte(b);                         // good byte (incl. ORE: DR still holds valid data)
	  }
	  return;   // USART3 RX bypasses HAL entirely; TX stays polled via HAL_UART_Transmit
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

